SET client_min_messages TO warning;
DROP SCHEMA IF EXISTS academico CASCADE;
CREATE SCHEMA academico;
SET search_path TO academico;

-- -----------------------------------------------------------------------------
-- Departamento
-- -----------------------------------------------------------------------------
CREATE TABLE departamento (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sigla   varchar(10)  NOT NULL UNIQUE,
    nome    varchar(100) NOT NULL
);

-- -----------------------------------------------------------------------------
-- Especialização total e disjunta: PESSOA -> {PROFESSOR, ALUNO}
-- Mapeada com uma tabela para a superclasse e uma por subclasse; a chave da
-- subclasse é ao mesmo tempo PK e FK para a superclasse.
-- A disjunção (ninguém é professor e aluno ao mesmo tempo) é garantida por
-- trigger em 06_views_funcoes_triggers.sql.
-- -----------------------------------------------------------------------------
CREATE TABLE pessoa (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             varchar(100) NOT NULL,
    email            varchar(120) NOT NULL UNIQUE
                     CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    data_nascimento  date NOT NULL
                     CHECK (data_nascimento > DATE '1900-01-01')
);

CREATE TABLE professor (
    pessoa_id        integer PRIMARY KEY REFERENCES pessoa (id) ON DELETE CASCADE,
    siape            char(7)  NOT NULL UNIQUE CHECK (siape ~ '^[0-9]{7}$'),
    departamento_id  integer  NOT NULL REFERENCES departamento (id),
    titulacao        varchar(10) NOT NULL
                     CHECK (titulacao IN ('Graduado', 'Mestre', 'Doutor')),
    salario          numeric(10, 2) NOT NULL CHECK (salario > 0),
    data_admissao    date NOT NULL
);

CREATE TABLE curso (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           varchar(10)  NOT NULL UNIQUE,
    nome             varchar(100) NOT NULL,
    departamento_id  integer NOT NULL REFERENCES departamento (id),
    -- relacionamento 1:1 "coordena" (um professor coordena no máximo um curso)
    coordenador_id   integer UNIQUE REFERENCES professor (pessoa_id) ON DELETE SET NULL
);

CREATE TABLE aluno (
    pessoa_id     integer PRIMARY KEY REFERENCES pessoa (id) ON DELETE CASCADE,
    matricula     char(9) NOT NULL UNIQUE CHECK (matricula ~ '^[0-9]{9}$'),
    curso_id      integer NOT NULL REFERENCES curso (id),
    ano_ingresso  smallint NOT NULL CHECK (ano_ingresso BETWEEN 2000 AND 2100)
);

-- -----------------------------------------------------------------------------
-- Disciplina e auto-relacionamento N:N "é pré-requisito de"
-- -----------------------------------------------------------------------------
CREATE TABLE disciplina (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           varchar(10)  NOT NULL UNIQUE,
    nome             varchar(100) NOT NULL,
    carga_horaria    smallint NOT NULL CHECK (carga_horaria > 0 AND carga_horaria % 15 = 0),
    departamento_id  integer  NOT NULL REFERENCES departamento (id)
);

CREATE TABLE pre_requisito (
    disciplina_id  integer REFERENCES disciplina (id) ON DELETE CASCADE,
    requisito_id   integer REFERENCES disciplina (id) ON DELETE CASCADE,
    PRIMARY KEY (disciplina_id, requisito_id),
    CHECK (disciplina_id <> requisito_id)
);

-- -----------------------------------------------------------------------------
-- Turma: oferta de uma disciplina em um semestre, ministrada por um professor
-- -----------------------------------------------------------------------------
CREATE TABLE turma (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disciplina_id  integer  NOT NULL REFERENCES disciplina (id),
    professor_id   integer  NOT NULL REFERENCES professor (pessoa_id),
    ano            smallint NOT NULL CHECK (ano BETWEEN 2000 AND 2100),
    semestre       smallint NOT NULL CHECK (semestre IN (1, 2)),
    codigo         char(1)  NOT NULL DEFAULT 'A',
    vagas          smallint NOT NULL CHECK (vagas > 0),
    UNIQUE (disciplina_id, ano, semestre, codigo)
);

-- -----------------------------------------------------------------------------
-- Matrícula: relacionamento N:N entre ALUNO e TURMA com atributos próprios.
-- A situação é uma coluna gerada (derivada de nota e frequência).
-- -----------------------------------------------------------------------------
CREATE TABLE matricula (
    aluno_id    integer REFERENCES aluno (pessoa_id) ON DELETE CASCADE,
    turma_id    integer REFERENCES turma (id) ON DELETE CASCADE,
    nota        numeric(4, 2) CHECK (nota BETWEEN 0 AND 10),
    frequencia  numeric(5, 2) CHECK (frequencia BETWEEN 0 AND 100),
    situacao    varchar(10) GENERATED ALWAYS AS (
                    CASE
                        WHEN nota IS NULL THEN 'CURSANDO'
                        WHEN nota >= 6 AND frequencia >= 75 THEN 'APROVADO'
                        ELSE 'REPROVADO'
                    END
                ) STORED,
    PRIMARY KEY (aluno_id, turma_id),
    -- nota e frequência são lançadas juntas
    CHECK ((nota IS NULL) = (frequencia IS NULL))
);

-- Histórico de alterações de nota (preenchido por trigger)
CREATE TABLE auditoria_nota (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    aluno_id      integer NOT NULL,
    turma_id      integer NOT NULL,
    nota_antiga   numeric(4, 2),
    nota_nova     numeric(4, 2),
    alterado_por  text        NOT NULL DEFAULT current_user,
    alterado_em   timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE  pessoa IS 'Superclasse da especialização total e disjunta {professor, aluno}';
COMMENT ON TABLE  pre_requisito IS 'Auto-relacionamento N:N de disciplina';
COMMENT ON COLUMN matricula.situacao IS 'Derivada: APROVADO se nota >= 6 e frequência >= 75%';
